/**
 * Generates `dist/tokens.css` from the TypeScript tokens.
 *
 * Web reads `var(--bg)`; React Native reads `theme.bg`. One source, two idioms,
 * each native to its platform (docs/adr/0002). Switching palette on web is a
 * single `data-palette` attribute on <html>.
 *
 * Run via `pnpm --filter @photu/tokens build` (and `task gen`). CI fails if the
 * committed output is stale.
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { elevation } from '../src/elevation'
import { webFontStacks } from '../src/fonts'
import { blur, buttonSizes, controls, tabBar } from '../src/layout'
import { duration, easing, timing } from '../src/motion'
import { DEFAULT_PALETTE, PALETTE_ORDER, PALETTES } from '../src/palettes'
import { componentRadii, radii } from '../src/radii'
import { overlay, semanticColors, toast, viewer } from '../src/semantic'
import { screenSpace, space } from '../src/space'
import { textStyles } from '../src/textStyles'

const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()

const COLOR_TOKENS = [
  'bg',
  'surface',
  'surfaceAlt',
  'ink',
  'inkSoft',
  'inkMuted',
  'line',
  'lineStrong',
  'accent',
  'accentInk',
  'accentSoft',
  'danger',
  'success',
] as const

const lines: string[] = [
  '/* GENERATED by packages/tokens/scripts/gen-css.ts — do not edit.',
  ' * Source of truth is packages/tokens/src/*.ts. Run `task gen` to regenerate.',
  ' */',
  '',
]

// ---------------------------------------------------------------- structural
// Palette-independent: type, radii, spacing, motion, geometry. Emitted once.
lines.push(':root {')
lines.push('  /* type */')
for (const [name, stack] of Object.entries(webFontStacks)) {
  lines.push(`  --font-${name}: ${stack};`)
}
for (const [name, style] of Object.entries(textStyles)) {
  const k = kebab(name)
  lines.push(`  --text-${k}-size: ${style.fontSize}px;`)
  if (style.lineHeight) lines.push(`  --text-${k}-line: ${style.lineHeight}px;`)
  if ('letterSpacing' in style && style.letterSpacing !== undefined) {
    lines.push(`  --text-${k}-tracking: ${style.letterSpacing}px;`)
  }
}
lines.push('', '  /* radii */')
for (const [name, v] of Object.entries(radii)) lines.push(`  --radius-${kebab(name)}: ${v}px;`)
for (const [name, v] of Object.entries(componentRadii)) {
  lines.push(`  --radius-${kebab(name)}: ${v}px;`)
}
lines.push('', '  /* spacing */')
for (const [name, v] of Object.entries(space)) lines.push(`  --space-${name}: ${v}px;`)
for (const [name, v] of Object.entries(screenSpace)) {
  lines.push(`  --space-${kebab(name)}: ${v}px;`)
}
lines.push('', '  /* motion */')
for (const [name, v] of Object.entries(duration)) lines.push(`  --duration-${name}: ${v}ms;`)
lines.push(`  --easing-standard: ${easing.standard};`)
for (const [name, v] of Object.entries(timing)) lines.push(`  --timing-${kebab(name)}: ${v}ms;`)
lines.push('', '  /* elevation */')
for (const [name, e] of Object.entries(elevation)) {
  lines.push(`  --shadow-${kebab(name)}: ${e.css};`)
}
lines.push('', '  /* geometry */')
for (const [name, v] of Object.entries(controls)) lines.push(`  --control-${kebab(name)}: ${v}px;`)
for (const [name, v] of Object.entries(blur)) lines.push(`  --blur-${kebab(name)}: ${v}px;`)
for (const [name, s] of Object.entries(buttonSizes)) {
  lines.push(`  --button-${name}-height: ${s.height}px;`)
  lines.push(`  --button-${name}-padding: ${s.paddingHorizontal}px;`)
}
lines.push(`  --tab-bar-height: ${tabBar.height}px;`)
lines.push('', '  /* over-photo overlays — fixed alphas, palette-independent */')
for (const [name, v] of Object.entries(overlay)) lines.push(`  --overlay-${kebab(name)}: ${v};`)
lines.push(`  --viewer-bg: ${viewer.bg};`)
lines.push(`  --viewer-ink: ${viewer.ink};`)
lines.push(`  --toast-bg: ${toast.bg};`)
lines.push(`  --toast-ink: ${toast.ink};`)
lines.push('}', '')

// -------------------------------------------------------------------- palettes
const emitPalette = (selector: string, key: (typeof PALETTE_ORDER)[number]) => {
  const p = PALETTES[key]
  const sem = semanticColors(p.isDark)
  lines.push(`${selector} {`)
  for (const t of COLOR_TOKENS) lines.push(`  --${kebab(t)}: ${p[t]};`)
  for (const [name, v] of Object.entries(sem)) lines.push(`  --${kebab(name)}: ${v};`)
  // Exposed so CSS can pick a blur tint and web can set <meta name=color-scheme>.
  lines.push(`  color-scheme: ${p.isDark ? 'dark' : 'light'};`)
  lines.push('}', '')
}

lines.push(`/* Default palette: ${DEFAULT_PALETTE}. Applied without any attribute. */`)
emitPalette(':root', DEFAULT_PALETTE)

lines.push('/* All palettes, selectable via <html data-palette="..."> */')
for (const key of PALETTE_ORDER) {
  emitPalette(`:root[data-palette='${key}']`, key)
}

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist')
mkdirSync(out, { recursive: true })
writeFileSync(join(out, 'tokens.css'), `${lines.join('\n')}\n`, 'utf8')
console.log(`wrote dist/tokens.css (${lines.length} lines, ${PALETTE_ORDER.length} palettes)`)
