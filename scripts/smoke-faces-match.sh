#!/usr/bin/env bash
# Face MATCHING end-to-end — the heart of face-privacy.
#
# Real faces, real embeddings, real matching. Two people:
#   A owns a face-privacy album. B uploads a reference selfie and joins the album.
#   A uploads a GROUP photo that contains B. The face worker must, unprompted:
#     - embed B's reference selfie,
#     - detect every face in the group photo,
#     - recognise B among them and write a SUGGESTED tag for B (never confirmed).
#
# And the trust invariant: a suggested tag does NOT yet grant visibility — media_subjects
# is written only from CONFIRMED tags — so B cannot see the photo until B confirms.
#
# Assets are generated by the caller from InsightFace's bundled group photo:
#   $SP/group.jpg   (the group photo, ~6 faces)
#   $SP/selfie.jpg  (a crop of one of those faces, used as B's reference)
#
# Needs: task api (host mode) + a FACE worker (uv run python -m mediaworker --kinds=face)
#        + the thumbnail worker. Run: task smoke:faces-match
set -euo pipefail

API="${API_BASE_URL:-http://localhost:8080}"
[ -f .env ] && { set -a; . ./.env; set +a; }
SP="${SP:-/private/tmp/claude-501/-Users-dharmikjethva-Desktop-photo/ebcc32c7-0fc1-40d2-b128-cffdd8fc276b/scratchpad}"

pass() { printf '\033[32m ok \033[0m %s\n' "$1"; }
fail() { printf '\033[31mFAIL\033[0m %s\n' "$1" >&2; exit 1; }
step() { printf '\n\033[36m==>\033[0m %s\n' "$1"; }

for c in curl jq; do command -v "$c" >/dev/null || fail "$c required"; done
curl -sf "$API/readyz" >/dev/null || fail "$API not up (task api)"

# Generate the test assets from InsightFace's bundled group photo if absent: a real
# multi-face image (the album photo) and a crop of one of its faces (B's reference).
# Self-contained so `task smoke:faces-match` needs no prior setup.
if [ ! -f "$SP/group.jpg" ] || [ ! -f "$SP/selfie.jpg" ]; then
  step "Generating test faces from InsightFace's sample image"
  ( cd services/mediaworker && SP="$SP" uv run python - <<'PY'
import os, warnings; warnings.filterwarnings("ignore")
import cv2
from insightface.app import FaceAnalysis
from insightface.data import get_image as ins_get_image
sp = os.environ["SP"]
app = FaceAnalysis(name="buffalo_l", providers=["CPUExecutionProvider"],
                   allowed_modules=["detection", "recognition"])
app.prepare(ctx_id=-1, det_size=(640, 640))
img = ins_get_image("t1")
faces = sorted(app.get(img), key=lambda f: -(f.bbox[2] - f.bbox[0]))
cv2.imwrite(f"{sp}/group.jpg", img)
f = faces[0]; x1, y1, x2, y2 = (int(v) for v in f.bbox)
px, py = int((x2 - x1) * 0.4), int((y2 - y1) * 0.4)
h, w = img.shape[:2]
cv2.imwrite(f"{sp}/selfie.jpg", img[max(0, y1-py):min(h, y2+py), max(0, x1-px):min(w, x2+px)])
PY
  ) >/dev/null 2>&1 || fail "could not generate test assets (is the face lane installed?)"
  pass "generated group.jpg + selfie.jpg"
fi

psql_() {
  docker compose exec -T postgres psql -qtAX -U "${POSTGRES_USER:-photu}" \
    -d "${POSTGRES_DB:-photu}" "$@" | tr -d '\r'
}
signin() {
  curl -sf -X POST "$API/v1/auth/apple" -H 'Content-Type: application/json' \
    -d "{\"idToken\":\"$1\"}"
}
# upload <token> <album> <clientId> <file> <ctype> -> mediaId
upload() {
  local tok="$1" album="$2" cid="$3" file="$4" ctype="$5" bytes url mid
  bytes=$(wc -c <"$file" | tr -d ' ')
  local d
  d=$(curl -sf -X POST "$API/v1/albums/$album/uploads" -H "Authorization: Bearer $tok" \
    -H 'Content-Type: application/json' \
    -d "{\"clientMediaId\":\"$cid\",\"contentType\":\"$ctype\",\"byteSize\":$bytes}")
  mid=$(echo "$d" | jq -r '.mediaId'); url=$(echo "$d" | jq -r '.upload.url')
  curl -sf -o /dev/null -X PUT -H "Content-Type: $ctype" --data-binary "@$file" "$url"
  curl -sf -X POST "$API/v1/uploads/$mid/complete" -H "Authorization: Bearer $tok" >/dev/null
  echo "$mid"
}

step "Two users; B uploads a reference selfie"
A=$(signin "faceA-$(date +%s)-$RANDOM" | jq -r '.accessToken')
BJSON=$(signin "faceB-$(date +%s)-$RANDOM"); B=$(echo "$BJSON" | jq -r '.accessToken')
BID=$(curl -sf -H "Authorization: Bearer $B" "$API/v1/me" | jq -r '.id')
curl -sf -X POST "$API/v1/me/face-consent" -H "Authorization: Bearer $B" >/dev/null
# reference upload (declare -> PUT -> complete)
rd=$(curl -sf -X POST "$API/v1/me/face-references" -H "Authorization: Bearer $B" \
  -H 'Content-Type: application/json' \
  -d "{\"contentType\":\"image/jpeg\",\"byteSize\":$(wc -c <"$SP/selfie.jpg" | tr -d ' ')}")
RID=$(echo "$rd" | jq -r '.referenceId'); RURL=$(echo "$rd" | jq -r '.upload.url')
curl -sf -o /dev/null -X PUT -H 'Content-Type: image/jpeg' --data-binary "@$SP/selfie.jpg" "$RURL"
curl -sf -X POST "$API/v1/me/face-references/$RID/complete" -H "Authorization: Bearer $B" \
  -H 'Content-Type: application/json' -d '{"contentType":"image/jpeg"}' >/dev/null
pass "user B $BID enrolled a reference selfie"

step "A creates a face-privacy album; B joins it"
ALBUM=$(curl -sf -X POST "$API/v1/albums" -H "Authorization: Bearer $A" \
  -H 'Content-Type: application/json' \
  -d '{"title":"Faces test","template":"trip","privacyMode":"face"}' | jq -r '.id')
CODE=$(curl -sf -X POST "$API/v1/albums/$ALBUM/invites" -H "Authorization: Bearer $A" \
  -H 'Content-Type: application/json' -d '{}' | jq -r '.code')
curl -sf -X POST "$API/v1/invites/$CODE/accept" -H "Authorization: Bearer $B" >/dev/null
[ "$(curl -sf "$API/v1/albums/$ALBUM/members" -H "Authorization: Bearer $A" | jq '.members|length')" = "2" ] \
  || fail "B did not join the album"
pass "album $ALBUM (face mode), 2 members"

step "A uploads a group photo containing B"
MID=$(upload "$A" "$ALBUM" "group-1" "$SP/group.jpg" "image/jpeg")
pass "photo $MID uploaded"

step "Waiting for the face worker to process it"
for _ in $(seq 1 60); do
  st=$(psql_ -c "SELECT face_proc_state FROM media_items WHERE id='$MID'")
  [ "$st" = "done" ] && break
  [ "$st" = "failed" ] && fail "face processing failed"
  sleep 2
done
[ "$st" = "done" ] || fail "face_proc_state still '$st' after 120s — is a --kinds=face worker running?"
pass "face_proc_state = done"

# B's reference must have been embedded (by the worker sweep / on-demand).
emb=$(psql_ -c "SELECT (embedding IS NOT NULL) FROM face_references WHERE id='$RID'")
[ "$emb" = "t" ] || fail "B's reference was never embedded"
pass "B's reference selfie was embedded"

# Faces were detected in the group photo.
nfaces=$(psql_ -c "SELECT count(*) FROM faces WHERE media_item_id='$MID'")
[ "$nfaces" -ge 4 ] || fail "only $nfaces faces detected in the group photo (expected several)"
pass "$nfaces faces detected in the group photo"

# THE MATCH: a SUGGESTED tag for B on this photo, above threshold, source auto.
read -r tstatus tsim tsource <<<"$(psql_ -c \
  "SELECT status, round(similarity::numeric,3), source FROM face_tags
    WHERE media_item_id='$MID' AND user_id='$BID' ORDER BY similarity DESC LIMIT 1" | tr '|' ' ')"
[ -n "$tstatus" ] || fail "B was NOT matched in the group photo — no face_tag for B"
[ "$tstatus" = "suggested" ] || fail "the tag is '$tstatus', expected 'suggested' (auto-match must never confirm)"
[ "$tsource" = "auto_match" ] || fail "tag source is '$tsource', expected 'auto'"
pass "B recognised in the group photo: suggested tag, similarity=$tsim (source=$tsource)"

# THE TRUST INVARIANT: a suggested tag grants NOTHING yet — B is not a media_subject,
# so B cannot see the photo until B confirms.
subj=$(psql_ -c "SELECT count(*) FROM media_subjects WHERE media_item_id='$MID' AND user_id='$BID'")
[ "$subj" = "0" ] || fail "a SUGGESTED match already granted visibility (media_subjects row exists) — it must not"
# And the feed proves it: B (a member) sees zero photos, because the only photo is one
# they're merely SUGGESTED in, not confirmed.
bfeed=$(curl -sf "$API/v1/albums/$ALBUM/media" -H "Authorization: Bearer $B" | jq '.items|length')
[ "$bfeed" = "0" ] || fail "B can see $bfeed photos from suggestions alone — face-privacy leak"
pass "suggested-only ≠ visible: B is not a subject and sees 0 photos until confirming"

echo
printf '\033[32m════ FACE MATCH SMOKE PASSED ════\033[0m\n'
echo "reference embedded · faces detected · B recognised (suggested) · no leak before confirm"
